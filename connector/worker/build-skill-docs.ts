import { execFileSync } from 'node:child_process';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { listSkills, readSkill } from '../src/catalog.js';

/**
 * Builds src/public-ui/skill-docs.ts: the plain text of every skill's SKILL.md (for /shopify-va/llms-full.txt and the
 * /shopify-va/skills/<slug> pages) and of every references/*.md file (for /shopify-va/skills/<slug>/references/<file>).
 * The Worker cannot read the filesystem, so the text is generated from skills/ and committed;
 * tests/public-llms.test.ts fails when the committed copy drifts from the source.
 */
export const SKILL_DOCS_FILE = resolve('src/public-ui/skill-docs.ts');

export async function collectSkillDocs(root: string) {
  const skills = await listSkills(root);
  return Promise.all(skills.map(async skill => {
    const text = (await readSkill(root, skill.name)).replace(/\r\n/g, '\n');
    const closing = text.indexOf('\n---', 4);
    return { slug: skill.name, description: skill.description, body: text.slice(closing + 4).trim() };
  }));
}

/** Every skills/<slug>/references/*.md file, sorted by skill then file name; `file` drops the .md extension. */
export async function collectSkillReferences(root: string) {
  const skills = await listSkills(root), out: { slug: string; file: string; body: string }[] = [];
  for (const skill of skills) {
    const names = await readdir(join(root, skill.name, 'references')).catch(() => [] as string[]);
    for (const name of names.filter(entry => /^[a-z0-9][a-z0-9-]*\.md$/.test(entry)).sort()) {
      const body = (await readFile(join(root, skill.name, 'references', name), 'utf8')).replace(/\r\n/g, '\n').trim();
      out.push({ slug: skill.name, file: name.slice(0, -3), body });
    }
  }
  return out;
}

export function renderSkillDocsModule(docs: Awaited<ReturnType<typeof collectSkillDocs>>, updated: string, references: Awaited<ReturnType<typeof collectSkillReferences>> = []): string {
  return `// GENERATED by worker/build-skill-docs.ts from skills/*/SKILL.md and skills/*/references/*.md. Do not edit; run \`npm run public:docs\`.
/** Date of the latest commit that touched skills/ when this file was generated (YYYY-MM-DD). */
export const SKILL_DOCS_UPDATED = ${JSON.stringify(updated)};
export const SKILL_DOCS: readonly { slug: string; description: string; body: string }[] = ${JSON.stringify(docs, null, 1)};
export const SKILL_REFERENCES: readonly { slug: string; file: string; body: string }[] = ${JSON.stringify(references, null, 1)};
`;
}

async function currentDate(root: string): Promise<string> {
  try {
    const date = execFileSync('git', ['log', '-1', '--format=%cs', '--', root], { encoding: 'utf8' }).trim();
    if (/^\d{4}-\d{2}-\d{2}$/.test(date)) return date;
  } catch { /* shallow clone or no git: keep the committed date */ }
  const previous = /SKILL_DOCS_UPDATED = "(\d{4}-\d{2}-\d{2})"/.exec(await readFile(SKILL_DOCS_FILE, 'utf8').catch(() => ''));
  return previous?.[1] ?? new Date().toISOString().slice(0, 10);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const root = resolve('../skills');
  const docs = await collectSkillDocs(root);
  const references = await collectSkillReferences(root);
  await writeFile(SKILL_DOCS_FILE, renderSkillDocsModule(docs, await currentDate(root), references));
  console.log(`Wrote ${docs.length} skill documents and ${references.length} reference files to ${SKILL_DOCS_FILE}.`);
}
